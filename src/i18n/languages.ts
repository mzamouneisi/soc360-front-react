export function findKnownLanguage(code: string): KnownLanguage | undefined {
  return KNOWN_LANGUAGES.find((language) => language.code === code)
}

export function filterKnownLanguages(query: string): KnownLanguage[] {
  const needle = query.trim().toLowerCase()
  if (!needle) return KNOWN_LANGUAGES
  return KNOWN_LANGUAGES.filter(
    (language) =>
      language.code.toLowerCase().includes(needle) ||
      language.label.toLowerCase().includes(needle),
  )
}
